/** Один вариант множественного выбора. */
export type Option = {
  /** Уникальное стабильное значение, используемое в value и onChange. */
  value: string;
  /** Текст варианта в меню. */
  label: string;
};

/** Выбранные значения управляются снаружи, открытие меню — внутри компонента. */
export type MultiSelectProps = {
  /** Подпись кнопки и доступное имя меню. */
  label: string;
  /** Варианты в порядке отображения; значения должны быть уникальны. */
  options: readonly Option[];
  /** Выбранные значения из options. Пустой массив означает отсутствие выбора. */
  value: readonly string[];
  /** Полный новый массив выбранных значений; сохраните его во внешнем состоянии. */
  onChange: (value: string[]) => void;
  /** Отключает кнопку и варианты выбора. По умолчанию false. */
  disabled?: boolean;
};
